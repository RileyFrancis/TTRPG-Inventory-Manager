#!/usr/bin/env node
// =============================================================================
// BUILD-FIREBASE-ENV — Writes firebase.env from environment variables
// =============================================================================
// For hosts that hand you configuration as build-time environment variables
// instead of a checked-in file. `.env` is gitignored, so it never reaches the
// deploy; and on Cloudflare Pages it could not be served even if it did, since
// Pages skips every path beginning with a dot. This writes the same key=value
// text to `firebase.env`, which is an ordinary filename and does get served.
//
// Cloudflare Pages → Settings → Builds:
//   Build command:            node tools/build-firebase-env.js
//   Build output directory:   /
// with the FIREBASE_* keys set under Variables and Secrets.
//
// Running it with none of those variables set is not an error: it writes
// nothing and the site deploys with party play switched off, exactly as a
// checkout with no `.env` runs locally.

'use strict';

const fs = require('fs');
const path = require('path');

const KEYS = [
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_DATABASE_URL',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
];

const outPath = path.join(__dirname, '..', 'firebase.env');

const present = KEYS.filter(k => (process.env[k] ?? '').trim() !== '');

// databaseURL is the one value party sync cannot work without — the same test
// firebase-config.js applies in the browser.
if (!present.includes('FIREBASE_DATABASE_URL')) {
  console.log('build-firebase-env: FIREBASE_DATABASE_URL is not set — writing nothing. ' +
              'The site will build fine; party play will be off.');
  process.exit(0);
}

const missing = KEYS.filter(k => !present.includes(k));
if (missing.length) {
  console.warn('build-firebase-env: no value for ' + missing.join(', ') + ' — party sync may misbehave.');
}

const body = present.map(k => `${k}=${process.env[k].trim()}`).join('\n');

fs.writeFileSync(outPath, `# Generated by tools/build-firebase-env.js — do not edit or commit.\n${body}\n`);
console.log(`build-firebase-env: wrote ${outPath} with ${present.length} of ${KEYS.length} keys.`);
